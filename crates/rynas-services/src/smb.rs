/// One `key = value` line.
pub type Line = (String, String);

fn l(k: &str, v: impl Into<String>) -> Line {
    (k.to_string(), v.into())
}

fn yes(b: bool) -> &'static str {
    if b { "yes" } else { "no" }
}

/// `NAS-01` style NetBIOS name from the host name (15 characters, upper case).
pub fn netbios_name(hostname: &str) -> String {
    let h: String = hostname
        .split('.')
        .next()
        .unwrap_or("")
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '-')
        .take(15)
        .collect();
    if h.is_empty() {
        "RYNAS".into()
    } else {
        h.to_ascii_uppercase()
    }
}

/// `[global]` lines.
pub fn global_lines(g: &SmbSettings, hostname: &str) -> Vec<Line> {
    let mut v = vec![
        l("server role", "standalone server"),
        l("workgroup", &g.workgroup),
        l(
            "server string",
            if g.server_string.is_empty() {
                "rynas %h".to_string()
            } else {
                g.server_string.clone()
            },
        ),
    ];
    if g.netbios {
        v.push(l("netbios name", netbios_name(hostname)));
    }
    v.extend([
        l("security", "user"),
        l("passdb backend", "tdbsam"),
        l("map to guest", "never"),
        // shadow expiry and disabled accounts apply to SMB too (pam_unix account)
        l("obey pam restrictions", "yes"),
        // rynas sets both passwords itself (chpasswd + pdbedit)
        l("unix password sync", "no"),
        l("server min protocol", &g.min_protocol),
    ]);
    if g.netbios {
        v.push(l("disable netbios", "no"));
    } else {
        v.push(l("disable netbios", "yes"));
        v.push(l("smb ports", "445"));
    }
    v.push(l("server multi channel support", "yes"));
    v.push(l(
        "server smb encrypt",
        if g.encryption_required {
            "required"
        } else {
            "default"
        },
    ));
    if !g.interfaces.is_empty() {
        let mut ifs = vec!["lo".to_string()];
        ifs.extend(g.interfaces.iter().cloned());
        v.push(l("interfaces", ifs.join(" ")));
        v.push(l("bind interfaces only", "yes"));
    }
    v.extend([
        // rynas writes the Avahi service file itself
        l("multicast dns register", "no"),
        l("access based share enum", "yes"),
        l("vfs objects", BASE_VFS.join(" ")),
        l("fruit:metadata", "stream"),
        l("fruit:nfs_aces", "no"),
        l("fruit:wipe_intentionally_left_blank_rfork", "yes"),
        l("fruit:delete_empty_adfiles", "yes"),
        l("fruit:model", "MacSamba"),
        l("inherit acls", "yes"),
        l("map acl inherit", "yes"),
        l("store dos attributes", "yes"),
        l("ea support", "yes"),
        l("spotlight backend", "noindex"),
        l("load printers", "no"),
        l("printing", "bsd"),
        l("printcap name", "/dev/null"),
        l("disable spoolss", "yes"),
        l("logging", "systemd"),
        l("log level", "1 auth_audit:3"),
    ]);
    if let Ok(extra) = smb_extra(&g.extra) {
        v.extend(extra.into_iter().map(|o| (o.key, o.value)));
    }
    v
}

fn regex_escape(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        if ".^$*+?()[]{}|\\".contains(c) {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// Default snapshot prefix of a share: the last component of its path.
pub fn shadow_prefix(s: &Share) -> String {
    if s.smb.shadow_copy.prefix.is_empty() {
        s.path.rsplit('/').next().unwrap_or("").to_string()
    } else {
        s.smb.shadow_copy.prefix.clone()
    }
}

/// Lines of a share section. `btrfs`: the path is on btrfs (server-side copies as reflinks
/// with vfs_btrfs).
pub fn share_lines(s: &Share, btrfs: bool) -> Vec<Line> {
    let smb = &s.smb;
    let mut v = vec![l("path", &s.path)];
    if !s.description.is_empty() {
        v.push(l("comment", &s.description));
    }
    v.push(l("browseable", yes(smb.browseable)));
    if s.permissions.is_empty() {
        v.push(l("read only", "no"));
    } else {
        let lists = smb_lists(&s.permissions);
        v.push(l("read only", "yes"));
        let list = |x: &[String]| x.join(" ");
        if !lists.valid.is_empty() {
            v.push(l("valid users", list(&lists.valid)));
        } else {
            // only denies: nobody may connect
            v.push(l("valid users", "root"));
        }
        if !lists.write.is_empty() {
            v.push(l("write list", list(&lists.write)));
        }
        if !lists.read.is_empty() {
            v.push(l("read list", list(&lists.read)));
        }
        if !lists.invalid.is_empty() {
            v.push(l("invalid users", list(&lists.invalid)));
        }
        // the default ACL decides: a narrower create mode would cut the ACL mask (the
        // default 0744 leaves group entries read-only on new files); files without x bits
        v.push(l("create mask", "0666"));
        v.push(l("directory mask", "0777"));
    }
    let shadow = smb.shadow_copy.enabled && !smb.shadow_copy.snapshot_dir.is_empty();
    let mut vfs: Vec<&str> = BASE_VFS.to_vec();
    if shadow {
        vfs.push("shadow_copy2");
    }
    if smb.recycle.enabled {
        vfs.push("recycle");
    }
    if btrfs {
        vfs.push("btrfs");
    }
    v.push(l("vfs objects", vfs.join(" ")));
    if smb.recycle.enabled {
        v.extend([
            l("recycle:repository", "#recycle"),
            l("recycle:keeptree", "yes"),
            l("recycle:versions", "yes"),
            l("recycle:touch", "yes"),
            l("recycle:directory_mode", "0770"),
            l("recycle:exclude", "*.tmp,~$*,.~lock*"),
        ]);
        if s.show_snapshots {
            // the snapshot folder is read-only: deletes there fail instead of being moved
            v.push(l("recycle:exclude_dir", rynas_api_types::SNAPSHOT_FOLDER));
        }
    }
    if shadow {
        v.extend([
            l("shadow:snapdir", &smb.shadow_copy.snapshot_dir),
            l(
                "shadow:snapprefix",
                format!("^{}$", regex_escape(&shadow_prefix(s))),
            ),
            l("shadow:delimiter", "."),
            l("shadow:format", SHADOW_FORMAT),
            l("shadow:localtime", "yes"),
            l("shadow:sort", "desc"),
        ]);
    }
    // the snapshot folder, when shown, is not vetoed (it is in the default veto list)
    let veto: Vec<&str> = smb
        .veto_files
        .iter()
        .map(String::as_str)
        .filter(|v| !(s.show_snapshots && *v == rynas_api_types::SNAPSHOT_FOLDER))
        .collect();
    if !veto.is_empty() {
        v.push(l("veto files", format!("/{}/", veto.join("/"))));
    }
    v.push(l("hide dot files", yes(smb.hide_dot_files)));
    if smb.encryption_required {
        v.push(l("server smb encrypt", "required"));
    }
    match smb.preset {
        SmbPreset::Standard => {}
        SmbPreset::Multiprotocol => v.extend([
            // NFS clients do not see SMB oplocks/leases: no client-side caching here (leases
            // need oplocks; `smb2 leases` itself is a global parameter)
            l("oplocks", "no"),
            l("level2 oplocks", "no"),
            l("kernel oplocks", "yes"),
        ]),
        SmbPreset::Timemachine => {
            v.push(l("fruit:time machine", "yes"));
            if !smb.timemachine_max_size.is_empty() {
                v.push(l("fruit:time machine max size", &smb.timemachine_max_size));
            }
        }
        SmbPreset::Hugefolders => v.extend([
            l("case sensitive", "yes"),
            l("preserve case", "yes"),
            l("short preserve case", "yes"),
        ]),
    }
    if let Ok(extra) = smb_extra(&smb.extra) {
        v.extend(extra.into_iter().map(|o| (o.key, o.value)));
    }
    v
}

/// Extra options that override a key rynas sets.
pub fn overridden_keys(managed: &[Line], extra: &str) -> Vec<String> {
    let keys: BTreeSet<&str> = managed.iter().map(|(k, _)| k.as_str()).collect();
    smb_extra(extra)
        .unwrap_or_default()
        .into_iter()
        .filter(|o| keys.contains(o.key.as_str()))
        .map(|o| o.key)
        .collect()
}

#[derive(Serialize)]
pub struct SmbShareCtx {
    pub name: String,
    pub lines: Vec<Line>,
}


//! `/etc/samba/smb.conf` and the Avahi service file.
//!
//! The lines are computed here (so that presets, VFS module order and access lists are
//! unit-tested) and laid out by small minijinja templates registered by the shares domain.
//! Samba 4.22 (Debian 13): no SMB1, NetBIOS off unless asked, fruit loaded on every share
//! (AAPL is negotiated per connection, and a share that sets `vfs objects` must repeat the
//! global modules), `#recycle`, `shadow_copy2` on btrbk snapshot names, POSIX ACLs
//! inherited (`inherit acls`), audit of authentications in the journal.

use std::collections::BTreeSet;

use rynas_api_types::{Share, SmbPreset, SmbSettings};
use serde::Serialize;

use crate::perm::smb_lists;
use crate::validate::smb_extra;

pub const SMB_CONF: &str = "/etc/samba/smb.conf";
pub const AVAHI_SERVICE: &str = "/etc/avahi/services/rynas-smb.service";

/// Modules every share loads, in this order (fruit before streams_xattr).
pub const BASE_VFS: [&str; 3] = ["catia", "fruit", "streams_xattr"];

/// Snapshot names of btrbk (`<prefix>.YYYYMMDDTHHMM`, `timestamp_format short`).
pub const SHADOW_FORMAT: &str = "%Y%m%dT%H%M";

pub const TEMPLATE_SMB: &str = "shares/smb.conf";
pub const TEMPLATE_AVAHI: &str = "shares/avahi.service";


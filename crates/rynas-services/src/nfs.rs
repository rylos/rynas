//! `/etc/exports.d/rynas.exports` and `/etc/nfs.conf.d/rynas.conf` (kernel nfsd).
//!
//! NFSv4.1/4.2 by default, v3 on demand (it brings rpcbind), fixed side-service ports for
//! the firewall. Every export gets `no_subtree_check`, `sec=sys` and an explicit
//! `fsid=<uuid>`: btrfs subvolumes share the filesystem UUID, so without it file handles of
//! different exports collide ("stale file handle" after a reboot).
//!
//! `exportfs` has no dry-run mode: every field is validated by rynas before rendering (the
//! client syntax, option values from enums only, quoted paths), and the apply runs
//! `exportfs -ra`, whose failure rolls the apply back.

use rynas_api_types::{NfsSettings, NfsSquash, Share};
use serde::Serialize;

pub const EXPORTS: &str = "/etc/exports.d/rynas.exports";
pub const NFS_CONF: &str = "/etc/nfs.conf.d/rynas.conf";

pub const TEMPLATE_EXPORTS: &str = "shares/exports";
pub const TEMPLATE_NFS_CONF: &str = "shares/nfs.conf";

pub const EXPORTS_TEMPLATE: &str = "\
# NFS exports generated by rynas from the `shares` configuration key.
{% for e in exports %}{{ e }}
{% endfor %}";

pub const NFS_CONF_TEMPLATE: &str = "\
# NFS server settings generated by rynas from the `shares` configuration key.
[nfsd]
threads = {{ threads }}
vers3 = {{ v3 }}
vers4 = y
vers4.0 = n
vers4.1 = y
vers4.2 = y

[mountd]
port = {{ mountd_port }}

[statd]
port = {{ statd_port }}
outgoing-port = {{ statd_out }}

[lockd]
port = {{ lockd_port }}
udp-port = {{ lockd_port }}
";

#[derive(Serialize)]
pub struct NfsConfCtx {
    pub threads: u32,
    pub v3: &'static str,
    pub mountd_port: u16,
    pub statd_port: u16,
    pub statd_out: u16,
    pub lockd_port: u16,
}

pub fn conf_ctx(n: &NfsSettings) -> NfsConfCtx {
    NfsConfCtx {
        threads: n.threads,
        v3: if n.v3 { "y" } else { "n" },
        mountd_port: n.mountd_port,
        statd_port: n.statd_port,
        statd_out: n.statd_port.saturating_add(1),
        lockd_port: n.lockd_port,
    }
}

/// The exports line of a share (`None` when NFS is off for it).
pub fn export_line(s: &Share) -> Option<String> {
    if !s.nfs.enabled || s.nfs.rules.is_empty() {
        return None;
    }
    let clients: Vec<String> = s
        .nfs
        .rules
        .iter()
        .map(|r| {
            let mut o = vec![
                if r.read_only { "ro" } else { "rw" }.to_string(),
                if r.sync { "sync" } else { "async" }.to_string(),
                "no_subtree_check".to_string(),
            ];
            match r.squash {
                NfsSquash::Root => o.push("root_squash".into()),
                NfsSquash::All => o.push("all_squash".into()),
                NfsSquash::None => o.push("no_root_squash".into()),
            }
            if r.squash != NfsSquash::None && (r.anonuid != 65534 || r.anongid != 65534) {
                o.push(format!("anonuid={}", r.anonuid));
                o.push(format!("anongid={}", r.anongid));
            }
            o.push("sec=sys".into());
            o.push(format!("fsid={}", s.nfs.fsid));
            if s.nfs.crossmnt {
                o.push("crossmnt".into());
            }
            format!("{}({})", r.client, o.join(","))
        })
        .collect();
    Some(format!("\"{}\" {}", s.path, clients.join(" ")))
}

#[cfg(test)]
mod tests {
    use super::*;
    use rynas_api_types::{NfsRule, ShareNfs};

    #[test]
    fn export_lines() {
        let s = Share {
            name: "media".into(),
            path: "/srv/vol1/media".into(),
            nfs: ShareNfs {
                enabled: true,
                fsid: "0f6c2b1e-1111-4222-8333-444455556666".into(),
                crossmnt: false,
                rules: vec![
                    NfsRule {
                        client: "192.168.1.0/24".into(),
                        ..Default::default()
                    },
                    NfsRule {
                        client: "tv.lan".into(),
                        read_only: true,
                        squash: NfsSquash::All,
                        anonuid: 1001,
                        anongid: 100,
                        sync: true,
                    },
                ],
            },
            ..Default::default()
        };
        assert_eq!(
            export_line(&s).unwrap(),
            "\"/srv/vol1/media\" 192.168.1.0/24(rw,sync,no_subtree_check,root_squash,sec=sys,\
             fsid=0f6c2b1e-1111-4222-8333-444455556666) \
             tv.lan(ro,sync,no_subtree_check,all_squash,anonuid=1001,anongid=100,sec=sys,\
             fsid=0f6c2b1e-1111-4222-8333-444455556666)"
        );
        let mut off = s.clone();
        off.nfs.enabled = false;
        assert!(export_line(&off).is_none());
    }
}

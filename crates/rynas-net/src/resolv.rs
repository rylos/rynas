//! Name resolution while systemd-networkd runs the network (D-NET; design in
//! `docs/research/network.md` §4.1).
//!
//! networkd hands the DNS servers it learns (DHCP, router advertisements, `DNS=` of the
//! settings) to systemd-resolved only: it never writes `/etc/resolv.conf`. On Debian 13
//! systemd-resolved is a separate package, often not installed, and ifupdown's DHCP client
//! (dhcpcd) leaves its own file behind, without servers once it released the lease. rynas
//! follows NetworkManager's `rc-manager=auto`:
//!
//! - systemd-resolved active: `/etc/resolv.conf` becomes the link to its stub file (what
//!   Tailscale and Docker expect: Docker reads the upstream servers of resolved by itself);
//! - otherwise rynas writes `/etc/resolv.conf` from networkd's per-link DNS servers and search
//!   domains, refreshed every minute by rynasd (no package to download, works offline).
//!
//! Only a file nobody else manages is touched: missing, empty, left over by dhcpcd, or written
//! by rynas. A file written by hand, by Tailscale, by resolvconf or any other link stays.

use std::net::{IpAddr, SocketAddr, UdpSocket};
use std::time::Duration;

/// The resolver file of glibc.
pub const RESOLV_CONF: &str = "/etc/resolv.conf";
/// systemd-resolved's stub file (`nameserver 127.0.0.53`).
pub const RESOLVED_STUB: &str = "/run/systemd/resolve/stub-resolv.conf";
/// systemd-resolved's upstream servers.
pub const RESOLVED_UPSTREAM: &str = "/run/systemd/resolve/resolv.conf";
/// First line of the file rynas writes.
pub const HEADER: &str = "# Generated by rynas from the DNS servers of systemd-networkd.";
/// glibc reads at most this many `nameserver` lines (`MAXNS`).
pub const MAXNS: usize = 3;

/// Who manages `/etc/resolv.conf`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Owner {
    Missing,
    /// Empty, or written by a DHCP client that no longer runs (dhcpcd under ifupdown).
    Leftover,
    Rynas,
    /// A link to systemd-resolved's files.
    Resolved,
    /// Anything else: the administrator, Tailscale, resolvconf... (what it is, for the logs).
    Other(String),
}

impl Owner {
    /// rynas may (re)write the file.
    pub fn replaceable(&self) -> bool {
        matches!(self, Owner::Missing | Owner::Leftover | Owner::Rynas)
    }
}

/// `content`: the file (following a link), `link`: the target when it is a symlink.
pub fn classify(content: Option<&str>, link: Option<&str>) -> Owner {
    if let Some(t) = link {
        return if t.contains("/run/systemd/resolve/") {
            Owner::Resolved
        } else {
            Owner::Other(format!("a link to {t}"))
        };
    }
    let Some(text) = content else {
        return Owner::Missing;
    };
    let comments: Vec<String> = text
        .lines()
        .map(str::trim)
        .filter(|l| l.starts_with('#') || l.starts_with(';'))
        .map(str::to_ascii_lowercase)
        .collect();
    if text.lines().next().map(str::trim) == Some(HEADER) {
        return Owner::Rynas;
    }
    if comments.iter().any(|l| l.contains("generated by tailscale")) {
        return Owner::Other("Tailscale".into());
    }
    if comments.iter().any(|l| l.contains("resolvconf")) {
        return Owner::Other("resolvconf".into());
    }
    if comments.iter().any(|l| l.contains("generated by dhcpcd")) {
        return Owner::Leftover;
    }
    let settings = text
        .lines()
        .map(str::trim)
        .any(|l| !l.is_empty() && !l.starts_with('#') && !l.starts_with(';'));
    if settings {
        Owner::Other("written by hand".into())
    } else {
        Owner::Leftover
    }
}

/// The address of a networkd DNS entry (`1.1.1.1`, `1.1.1.1:53#dns.example`,
/// `fe80::1%2`, `[2001:db8::1]:53`), as resolv.conf takes it; `None` when unusable.
pub fn server_addr(entry: &str) -> Option<String> {
    let e = entry.split('#').next().unwrap_or("").trim();
    if e.is_empty() {
        return None;
    }
    if let Some(rest) = e.strip_prefix('[') {
        let (addr, _) = rest.split_once(']')?;
        return valid(addr);
    }
    if e.matches(':').count() == 1 {
        // IPv4 with a port
        return valid(e.split(':').next().unwrap_or(""));
    }
    valid(e)
}

fn valid(a: &str) -> Option<String> {
    let ip = a.split('%').next().unwrap_or("");
    ip.parse::<IpAddr>().ok().map(|_| a.to_string())
}

/// The file rynas writes.
pub fn render(servers: &[String], search: &[String]) -> String {
    let mut s = format!(
        "{HEADER}\n# rynas keeps it up to date while it runs the network; replace it to manage it yourself.\n"
    );
    if !search.is_empty() {
        s.push_str(&format!("search {}\n", search.join(" ")));
    }
    for n in servers.iter().take(MAXNS) {
        s.push_str(&format!("nameserver {n}\n"));
    }
    s
}

/// A DNS query for the root's NS records (every resolver answers it, even offline with
/// SERVFAIL or REFUSED: an answer proves the server is reachable and speaks DNS).
pub fn query_packet(id: u16) -> Vec<u8> {
    let mut p = Vec::with_capacity(17);
    p.extend_from_slice(&id.to_be_bytes());
    p.extend_from_slice(&[0x01, 0x00]); // RD
    p.extend_from_slice(&[0, 1, 0, 0, 0, 0, 0, 0]); // one question
    p.push(0); // root
    p.extend_from_slice(&[0, 2, 0, 1]); // NS, IN
    p
}

/// `buf` is the answer to the query `id`.
pub fn is_answer(id: u16, buf: &[u8]) -> bool {
    buf.len() >= 12 && buf[..2] == id.to_be_bytes() && buf[2] & 0x80 != 0
}

/// Whether `server` (as in resolv.conf) answers a DNS query over UDP within `timeout`.
pub fn probe(server: &str, timeout: Duration) -> bool {
    let (ip, scope) = match server.split_once('%') {
        Some((a, s)) => (a, Some(s)),
        None => (server, None),
    };
    let Ok(ip) = ip.parse::<IpAddr>() else {
        return false;
    };
    let addr = match (ip, scope) {
        (IpAddr::V6(v6), Some(s)) => {
            let idx = s.parse::<u32>().ok().or_else(|| {
                let c = std::ffi::CString::new(s).ok()?;
                // SAFETY: a valid NUL-terminated string
                let i = unsafe { libc::if_nametoindex(c.as_ptr()) };
                (i != 0).then_some(i)
            });
            SocketAddr::V6(std::net::SocketAddrV6::new(v6, 53, 0, idx.unwrap_or(0)))
        }
        _ => SocketAddr::new(ip, 53),
    };
    let bind: SocketAddr = if addr.is_ipv4() {
        "0.0.0.0:0".parse().expect("address")
    } else {
        "[::]:0".parse().expect("address")
    };
    let Ok(sock) = UdpSocket::bind(bind) else {
        return false;
    };
    if sock.set_read_timeout(Some(timeout)).is_err() || sock.connect(addr).is_err() {
        return false;
    }
    let mut idb = [0u8; 2];
    if getrandom::fill(&mut idb).is_err() {
        return false;
    }
    let id = u16::from_be_bytes(idb);
    if sock.send(&query_packet(id)).is_err() {
        return false;
    }
    let deadline = std::time::Instant::now() + timeout;
    let mut buf = [0u8; 512];
    while std::time::Instant::now() < deadline {
        match sock.recv(&mut buf) {
            Ok(n) if is_answer(id, &buf[..n]) => return true,
            Ok(_) => continue,
            Err(_) => return false,
        }
    }
    false
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn owners() {
        assert_eq!(classify(None, None), Owner::Missing);
        assert_eq!(classify(Some(""), None), Owner::Leftover);
        // what dhcpcd leaves after releasing the lease at shutdown
        let dhcpcd = "# Generated by dhcpcd\n# /etc/resolv.conf.head can replace this line\n# /etc/resolv.conf.tail can replace this line\n";
        assert_eq!(classify(Some(dhcpcd), None), Owner::Leftover);
        // with a line added by hand to get going again: still dhcpcd's file
        let patched = format!("{dhcpcd}nameserver 192.0.2.10\n");
        assert_eq!(classify(Some(&patched), None), Owner::Leftover);
        assert_eq!(
            classify(Some(&render(&["192.0.2.1".into()], &[])), None),
            Owner::Rynas
        );
        assert_eq!(
            classify(Some("nameserver 192.0.2.1\n"), None),
            Owner::Other("written by hand".into())
        );
        assert!(!classify(Some("nameserver 192.0.2.1\n"), None).replaceable());
        assert_eq!(
            classify(
                Some("# resolv.conf(5) file generated by tailscale\nnameserver 100.100.100.100\n"),
                None
            ),
            Owner::Other("Tailscale".into())
        );
        assert_eq!(
            classify(
                Some("# Dynamic resolv.conf(5) file for glibc resolver(3) generated by resolvconf(8)\n"),
                None
            ),
            Owner::Other("resolvconf".into())
        );
        assert_eq!(
            classify(Some("nameserver 127.0.0.53\n"), Some(RESOLVED_STUB)),
            Owner::Resolved
        );
        assert!(matches!(
            classify(Some(""), Some("/run/resolvconf/resolv.conf")),
            Owner::Other(_)
        ));
    }

    #[test]
    fn servers_and_file() {
        assert_eq!(server_addr("192.0.2.1").as_deref(), Some("192.0.2.1"));
        assert_eq!(
            server_addr("192.0.2.1:853#dns.example").as_deref(),
            Some("192.0.2.1")
        );
        assert_eq!(server_addr("fe80::1%2").as_deref(), Some("fe80::1%2"));
        assert_eq!(
            server_addr("[2001:db8::1]:53#x").as_deref(),
            Some("2001:db8::1")
        );
        assert_eq!(server_addr("2001:db8::53").as_deref(), Some("2001:db8::53"));
        assert_eq!(server_addr("dns.example"), None);
        let f = render(
            &["192.0.2.1".into(), "192.0.2.2".into(), "192.0.2.3".into(), "192.0.2.4".into()],
            &["lan.example".into()],
        );
        assert!(f.starts_with(HEADER));
        assert!(f.contains("search lan.example\n"));
        assert_eq!(f.matches("nameserver").count(), MAXNS);
    }

    #[test]
    fn packet() {
        let p = query_packet(0x1234);
        assert_eq!(p.len(), 17);
        assert_eq!(&p[..2], &[0x12, 0x34]);
        let mut answer = p.clone();
        answer[2] |= 0x80;
        assert!(is_answer(0x1234, &answer));
        assert!(!is_answer(0x1234, &p), "a query is not an answer");
        assert!(!is_answer(0x4321, &answer));
        assert!(!probe("not-an-address", Duration::from_millis(10)));
    }
}

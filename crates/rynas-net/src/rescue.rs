//! Rescue paths that are always on.
//!
//! - Link-local: every rynas `.network` file has `LinkLocalAddressing=yes` and a deterministic
//!   `IPv4LLStartAddress=` ([`crate::networkd::link_local_for_mac`]).
//! - mDNS: avahi-daemon publishes `<host>.local` by itself; rynas adds a service file
//!   (`/etc/avahi/services/rynas.service`: `_rynas._tcp` and `_http._tcp`/`_https._tcp` on the
//!   web port) through the configuration key `network.rescue` ([`RescueDomain`]).
//! - Reset button (where a hardware module wires one to `rynasctl net reset-button`): one
//!   call per press (the hardware sends one event per press and never its length), so the
//!   gesture is a **double press within 10 s** timed here ([`classify`]): the first press asks
//!   for the second ([`Signal::PressAgain`]), the second restores the factory network (DHCP +
//!   link-local on every port, the previous configuration kept as a revision). The button's
//!   wiring is the module's own setting, never written here.
//! - [`Feedback`]: what the machine shows or sounds at those moments (a module's beeps and
//!   LEDs); [`NoFeedback`] elsewhere.

use rynas_api_types::network::RescueSettings;
use rynas_config::{Applier, ApplyCtx, ManagedFile};
use serde_json::Value;

/// Configuration key of the rescue settings.
pub const RESCUE_KEY: &str = "network.rescue";
pub const AVAHI_FILE: &str = "/etc/avahi/services/rynas.service";

/// Second press within this window after the first: factory network.
pub const GESTURE_WINDOW_MS: u64 = 10_000;
/// Presses closer than this are one press (a bouncing contact, a repeated event).
pub const BOUNCE_MS: u64 = 1_000;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Press {
    /// Starts the window: short beep, orange blink.
    First,
    /// Too close to the previous one: ignored.
    Bounce,
    /// Within the window: factory network.
    Second,
}

/// Classifies a press at `now` given the time of the previous first press.
pub fn classify(now_ms: u64, previous_ms: Option<u64>) -> Press {
    match previous_ms {
        Some(p) if now_ms >= p && now_ms - p < BOUNCE_MS => Press::Bounce,
        Some(p) if now_ms >= p && now_ms - p <= GESTURE_WINDOW_MS => Press::Second,
        _ => Press::First,
    }
}

/// A moment of the rescue paths the machine can signal (sound, LED).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Signal {
    /// First press of the reset button: press again within the window.
    PressAgain,
    /// Second press: the factory network is being restored.
    Restoring,
    /// The watchdog applied the rescue configuration (no routable address after boot).
    RescueApplied,
}

/// How the machine signals [`Signal`]s (a hardware module's beeps and LEDs). Fire and
/// forget: a missing executor is not an error.
pub trait Feedback: Send + Sync {
    fn signal(&self, s: Signal);
}

/// Machines without a way to signal.
pub struct NoFeedback;

impl Feedback for NoFeedback {
    fn signal(&self, _: Signal) {}
}

/// The Avahi service file.
pub fn avahi_service(port: u16, https: bool) -> String {
    let web = if https { "_https._tcp" } else { "_http._tcp" };
    format!(
        r#"<?xml version="1.0" standalone="no"?>
<!DOCTYPE service-group SYSTEM "avahi-service.dtd">
<!-- generated by rynas (configuration key network.rescue): web interface announcement -->
<service-group>
  <name replace-wildcards="yes">rynas on %h</name>
  <service>
    <type>_rynas._tcp</type>
    <port>{port}</port>
    <txt-record>path=/</txt-record>
  </service>
  <service>
    <type>{web}</type>
    <port>{port}</port>
    <txt-record>path=/</txt-record>
  </service>
</service-group>
"#
    )
}

fn settings_of(v: &Value) -> Result<RescueSettings, String> {
    serde_json::from_value(v.clone()).map_err(|e| format!("invalid rescue settings: {e}"))
}

/// `network.rescue`: the Avahi service file.
pub struct RescueDomain {
    pub web_port: u16,
    pub https: bool,
}

impl Applier for RescueDomain {
    fn key(&self) -> &str {
        RESCUE_KEY
    }

    fn order(&self) -> i32 {
        50
    }

    fn validate(&self, value: Value) -> Result<Value, rynas_config::Invalid> {
        serde_json::to_value(settings_of(&value)?).map_err(|e| e.to_string().into())
    }

    fn render(&self, value: &Value, _ctx: &ApplyCtx) -> Result<Vec<ManagedFile>, String> {
        let s = settings_of(value)?;
        Ok(vec![if s.mdns_service {
            ManagedFile::whole(AVAHI_FILE, avahi_service(self.web_port, self.https), false)
        } else {
            ManagedFile::absent(AVAHI_FILE)
        }])
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn double_press_timing() {
        assert_eq!(classify(50_000, None), Press::First);
        assert_eq!(classify(50_400, Some(50_000)), Press::Bounce);
        assert_eq!(classify(51_000, Some(50_000)), Press::Second);
        assert_eq!(classify(60_000, Some(50_000)), Press::Second);
        assert_eq!(classify(60_001, Some(50_000)), Press::First);
        // a clock that went backwards starts over
        assert_eq!(classify(40_000, Some(50_000)), Press::First);
    }

    #[test]
    fn rescue_key_through_the_configuration_store() {
        use std::sync::Arc;
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path().join("root");
        std::fs::create_dir_all(root.join("etc")).unwrap();
        // a hardware module's own file (synohwd's on a Synology) is never touched here
        let synohwd = "fan_mode = \"low\"\nreset_button = \"ignore\"\n";
        std::fs::write(root.join("etc/synohwd.toml"), synohwd).unwrap();
        let sys = Arc::new(rynas_config::MemorySystem::new("nas"));
        let cfg = rynas_config::Config::open(
            rynas_config::ConfigOptions::new(dir.path().join("state"), &root),
            sys.clone(),
            vec![Arc::new(RescueDomain {
                web_port: 8080,
                https: false,
            })],
        )
        .unwrap();
        let v = serde_json::to_value(RescueSettings::default()).unwrap();
        cfg.apply_value("rynas", RESCUE_KEY, Some(v), "defaults", &|_| {})
            .unwrap();
        assert!(
            std::fs::read_to_string(root.join("etc/avahi/services/rynas.service"))
                .unwrap()
                .contains("_rynas._tcp")
        );
        // a value of an older revision still has `reset_button`: read without it
        let old = serde_json::json!({"reset_button": true, "mdns_service": false});
        cfg.apply_value("rynas", RESCUE_KEY, Some(old), "", &|_| {})
            .unwrap();
        assert_eq!(
            cfg.applied(RESCUE_KEY).unwrap().unwrap(),
            serde_json::json!({"mdns_service": false})
        );
        assert!(!root.join("etc/avahi/services/rynas.service").exists());
        assert_eq!(
            std::fs::read_to_string(root.join("etc/synohwd.toml")).unwrap(),
            synohwd
        );
        assert!(sys.state().calls.iter().all(|c| !c.contains("synohwd")));
        assert!(cfg.drift().unwrap().entries.is_empty());
    }

    #[test]
    fn avahi_file() {
        let s = avahi_service(8080, false);
        assert!(s.contains("<type>_rynas._tcp</type>\n    <port>8080</port>"));
        assert!(s.contains("_http._tcp"));
        assert!(avahi_service(8443, true).contains("_https._tcp"));
    }
}

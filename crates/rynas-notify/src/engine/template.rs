//! Message texts: minijinja templates with the words of every language of the interface's
//! table (English here, the others from their translation files, `build.rs`).
//!
//! One subject and one body template for every channel; the language of a target picks the
//! dictionary (`t.*`) and the labels of severities, categories and states. Webhooks may
//! bring their own templates (URL, headers, body) rendered with the same context plus
//! `secrets`.

use std::collections::BTreeMap;

use minijinja::{Environment, Value, context};
use rynas_api_types::notify::{
    BodyFormat, EventState, Notification, NotifyLanguage, NotifySeverity, event_text,
};
use serde::Serialize;

use super::LocalTime;

const SUBJECT: &str = "[{{ hostname }}] {% if events|length == 1 %}{{ events[0].prefix }}{{ events[0].title }}\
{% else %}{{ events|length }} {{ t.notifications }} ({{ severity_label }}){% endif %}";

const BODY: &str =
    "{% for e in events %}{{ e.severity_label }} | {{ e.category_label }} | {{ e.time }}\
{% if e.count > 1 %} | {{ e.count }}x{% endif %}
{{ e.prefix }}{{ e.title }}
{% if e.body %}{{ e.body }}
{% endif %}{% for k, v in e.fields|items %}  {{ k }}: {{ v }}
{% endfor %}
{% endfor %}-- {{ '' }}
{{ t.footer }} {{ hostname }}
";

/// Words of one language.
struct Dict {
    notifications: &'static str,
    footer: &'static str,
    resolved: &'static str,
    reminder: &'static str,
    test_title: &'static str,
    test_body: &'static str,
    severity: [&'static str; 5],
    category: [&'static str; 9],
}

/// The source texts; every other language has them in its `notify.txt` (`notify.<field>`,
/// `notify.severity.<name>`, `notify.category.<name>`, docs/i18n.md).
const EN: Dict = Dict {
    notifications: "notifications",
    footer: "rynas on",
    resolved: "Resolved",
    reminder: "Reminder",
    test_title: "Test notification",
    test_body: "If you can read this, the channel works.",
    severity: ["Info", "Notice", "Warning", "Error", "Critical"],
    category: [
        "Storage", "Hardware", "UPS", "System", "Security", "Updates", "Backup", "Apps", "Tasks",
    ],
};

/// The key names of [`Dict::severity`] and [`Dict::category`], in the same order.
fn severity_key(i: usize) -> &'static str {
    NotifySeverity::ALL[i].as_str()
}

fn category_key(i: usize) -> &'static str {
    rynas_api_types::notify::NotifyCategory::ALL[i].as_str()
}

/// Per language of the table but English: `(key, text)` of the web interface's event texts
/// (`nev.*`), task names (`task.*`) and the template words (`notify.*`), sorted by key;
/// generated by `build.rs` from the translation files (`crates/rynas-ui/assets/i18n`).
static TEXTS: &[(&str, &[(&str, &str)])] = include!(concat!(env!("OUT_DIR"), "/event_texts.rs"));

/// The codes of the language table, English first.
pub static LANGUAGES: &[&str] = include!(concat!(env!("OUT_DIR"), "/languages.rs"));

/// The text of `key` in `lang`, `None` for English or where the language has none.
fn lookup(lang: NotifyLanguage, key: &str) -> Option<&'static str> {
    let (_, texts) = TEXTS.iter().find(|(c, _)| *c == lang.as_str())?;
    texts
        .binary_search_by(|e| e.0.cmp(key))
        .ok()
        .map(|i| texts[i].1)
        .filter(|t| !t.is_empty())
}

/// Whether a target may use `lang`: English or a language of the table.
pub fn known_language(lang: NotifyLanguage) -> bool {
    lang == NotifyLanguage::EN || LANGUAGES.contains(&lang.as_str())
}

/// Title and body of an event in a target's language: from the event code and its fields (the
/// web interface's rules, [`event_text`]) when the language has the texts, the English text
/// otherwise. Log bodies (command output) are sent as they are.
fn texts(n: &Notification, lang: NotifyLanguage) -> (String, String) {
    if lang == NotifyLanguage::EN {
        return (n.title.clone(), n.body.clone());
    }
    let find = |k: &str| lookup(lang, k);
    let title =
        event_text(&n.code, "title", &n.fields, &find, true).unwrap_or_else(|| n.title.clone());
    let body = match n.body_format {
        BodyFormat::Log => None,
        BodyFormat::Text => event_text(&n.code, "body", &n.fields, &find, true),
    }
    .unwrap_or_else(|| n.body.clone());
    (title, body)
}

/// The words of `l`, English where it has none.
fn dict(l: NotifyLanguage) -> Dict {
    let w = |k: &str, en: &'static str| lookup(l, &format!("notify.{k}")).unwrap_or(en);
    Dict {
        notifications: w("notifications", EN.notifications),
        footer: w("footer", EN.footer),
        resolved: w("resolved", EN.resolved),
        reminder: w("reminder", EN.reminder),
        test_title: w("test_title", EN.test_title),
        test_body: w("test_body", EN.test_body),
        severity: std::array::from_fn(|i| w(&format!("severity.{}", severity_key(i)), EN.severity[i])),
        category: std::array::from_fn(|i| w(&format!("category.{}", category_key(i)), EN.category[i])),
    }
}

/// The English source of the `notify` part, `(key, text)`: the checks of the translations.
pub fn notify_source() -> Vec<(String, &'static str)> {
    let mut v = vec![
        ("notify.notifications".to_string(), EN.notifications),
        ("notify.footer".to_string(), EN.footer),
        ("notify.resolved".to_string(), EN.resolved),
        ("notify.reminder".to_string(), EN.reminder),
        ("notify.test_title".to_string(), EN.test_title),
        ("notify.test_body".to_string(), EN.test_body),
    ];
    v.extend((0..5).map(|i| (format!("notify.severity.{}", severity_key(i)), EN.severity[i])));
    v.extend((0..9).map(|i| (format!("notify.category.{}", category_key(i)), EN.category[i])));
    v
}

/// Title and body of the test message of a target.
pub fn test_texts(l: NotifyLanguage) -> (&'static str, &'static str) {
    let d = dict(l);
    (d.test_title, d.test_body)
}

/// One event as templates see it.
#[derive(Debug, Clone, Serialize)]
pub struct EventCtx {
    pub id: u64,
    pub title: String,
    pub body: String,
    pub source: String,
    pub key: String,
    pub category: &'static str,
    pub category_label: &'static str,
    pub severity: &'static str,
    pub severity_label: &'static str,
    pub state: &'static str,
    /// "Resolved: ", "Reminder: " or "".
    pub prefix: String,
    /// Local time, "YYYY-MM-DD HH:MM".
    pub time: String,
    pub ts_ms: u64,
    pub count: u32,
    pub reminder: bool,
    pub fields: BTreeMap<String, String>,
}

/// A rendered message for one target.
#[derive(Debug, Clone)]
pub struct Message {
    pub subject: String,
    pub text: String,
    /// The highest severity among the events.
    pub severity: NotifySeverity,
    pub events: Vec<EventCtx>,
}

pub struct Templates {
    env: Environment<'static>,
    hostname: String,
}

pub fn fmt_time(t: LocalTime) -> String {
    format!(
        "{:04}-{:02}-{:02} {:02}:{:02}",
        t.year, t.month, t.day, t.hour, t.minute
    )
}

impl Templates {
    pub fn new(hostname: &str) -> Self {
        let mut env = Environment::new();
        env.set_auto_escape_callback(|_| minijinja::AutoEscape::None);
        env.add_template("subject", SUBJECT)
            .expect("built-in subject template");
        env.add_template("body", BODY)
            .expect("built-in body template");
        Self {
            env,
            hostname: hostname.to_string(),
        }
    }

    pub fn hostname(&self) -> &str {
        &self.hostname
    }

    /// The context of one event.
    pub fn event_ctx(
        &self,
        n: &Notification,
        reminder: bool,
        lang: NotifyLanguage,
        local: fn(u64) -> LocalTime,
    ) -> EventCtx {
        let d = dict(lang);
        let prefix = if reminder {
            format!("{}: ", d.reminder)
        } else if n.state == EventState::Resolved {
            format!("{}: ", d.resolved)
        } else {
            String::new()
        };
        let ci = rynas_api_types::notify::NotifyCategory::ALL
            .iter()
            .position(|c| *c == n.category)
            .unwrap_or(3);
        let (title, body) = texts(n, lang);
        EventCtx {
            id: n.id,
            title,
            body,
            source: n.source.clone(),
            key: n.key.clone(),
            category: n.category.as_str(),
            category_label: d.category[ci],
            severity: n.severity.as_str(),
            severity_label: d.severity[n.severity as usize],
            state: n.state.as_str(),
            prefix,
            time: fmt_time(local(n.ts_ms)),
            ts_ms: n.ts_ms,
            count: n.count,
            reminder,
            fields: n.fields.clone(),
        }
    }

    fn base_ctx(&self, events: &[EventCtx], lang: NotifyLanguage, sev: NotifySeverity) -> Value {
        let d = dict(lang);
        context! {
            hostname => &self.hostname,
            events => Value::from(minijinja::value::Serde(events)),
            severity => sev.as_str(),
            severity_label => d.severity[sev as usize],
            t => context! {
                notifications => d.notifications,
                footer => d.footer,
                resolved => d.resolved,
                reminder => d.reminder,
            },
        }
    }

    /// Subject and body of a message carrying `events` (at least one).
    pub fn render(&self, events: Vec<EventCtx>, lang: NotifyLanguage) -> Message {
        let severity = events
            .iter()
            .filter_map(|e| NotifySeverity::parse(e.severity))
            .max()
            .unwrap_or_default();
        let ctx = self.base_ctx(&events, lang, severity);
        let render = |name: &str| {
            self.env
                .get_template(name)
                .and_then(|t| t.render(&ctx))
                .unwrap_or_else(|e| {
                    tracing::error!("notification template {name}: {e}");
                    events.first().map(|e| e.title.clone()).unwrap_or_default()
                })
        };
        let subject = render("subject").replace(['\r', '\n'], " ");
        // minijinja drops the final newline of a template
        let text = render("body") + "\n";
        Message {
            subject,
            text,
            severity,
            events,
        }
    }

    /// Renders a user template (webhook URL, header or body) with the message context and
    /// the target's secrets.
    pub fn render_user(
        &self,
        source: &str,
        msg: &Message,
        lang: NotifyLanguage,
        secrets: &BTreeMap<String, String>,
    ) -> Result<String, String> {
        let base = self.base_ctx(&msg.events, lang, msg.severity);
        let ctx = context! {
            subject => &msg.subject,
            message => &msg.text,
            secrets => Value::from(minijinja::value::Serde(secrets)),
            ..base
        };
        self.env
            .render_str(source, ctx)
            .map_err(|e| format!("template: {e}"))
    }

    /// Checks that a user template compiles.
    pub fn check_user(&self, source: &str) -> Result<(), String> {
        self.env
            .template_from_str(source)
            .map(|_| ())
            .map_err(|e| format!("template: {e}"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use rynas_api_types::notify::NotifyCategory;

    fn utc(ms: u64) -> LocalTime {
        super::super::utc_time(ms)
    }

    fn n(id: u64, state: EventState) -> Notification {
        Notification {
            id,
            ts_ms: 1_762_300_800_000, // 2025-11-05 00:00 UTC
            count: 1,
            source: "storage".into(),
            category: NotifyCategory::Storage,
            severity: NotifySeverity::Critical,
            key: "storage:md:md2:health".into(),
            state,
            title: "RAID md2 degraded".into(),
            body: "1 of 2 members missing.".into(),
            fields: [("array".to_string(), "md2".to_string())].into(),
            ..Default::default()
        }
    }

    #[test]
    fn english_and_italian() {
        let t = Templates::new("nas");
        let ev = vec![t.event_ctx(&n(1, EventState::Firing), false, NotifyLanguage::EN, utc)];
        let m = t.render(ev, NotifyLanguage::EN);
        assert_eq!(m.subject, "[nas] RAID md2 degraded");
        assert_eq!(
            m.text,
            "Critical | Storage | 2025-11-05 00:00\nRAID md2 degraded\n1 of 2 members missing.\n  array: md2\n\n-- \nrynas on nas\n"
        );
        let ev = vec![
            t.event_ctx(&n(1, EventState::Resolved), false, NotifyLanguage::new("it").unwrap(), utc),
            t.event_ctx(&n(2, EventState::Firing), true, NotifyLanguage::new("it").unwrap(), utc),
        ];
        let m = t.render(ev, NotifyLanguage::new("it").unwrap());
        assert_eq!(m.subject, "[nas] 2 notifiche (Critico)");
        assert!(
            m.text
                .contains("Critico | Archiviazione | 2025-11-05 00:00\nRisolto: RAID md2 degraded")
        );
        assert!(m.text.contains("Promemoria: RAID md2 degraded"));
        assert!(m.text.ends_with("-- \nrynas su nas\n"));
    }

    #[test]
    fn user_templates_see_secrets() {
        let t = Templates::new("nas");
        let ev = vec![t.event_ctx(&n(1, EventState::Firing), false, NotifyLanguage::EN, utc)];
        let m = t.render(ev, NotifyLanguage::EN);
        let s: BTreeMap<String, String> = [("token".to_string(), "s3cr3t".to_string())].into();
        let out = t
            .render_user(
                "{\"text\": {{ subject|tojson }}, \"sev\": \"{{ severity }}\", \"k\": \"{{ secrets.token }}\", \"n\": {{ events|length }}}",
                &m,
                NotifyLanguage::EN,
                &s,
            )
            .unwrap();
        assert_eq!(
            out,
            "{\"text\": \"[nas] RAID md2 degraded\", \"sev\": \"critical\", \"k\": \"s3cr3t\", \"n\": 1}"
        );
        assert!(t.check_user("{% if %}").is_err());
    }

    #[test]
    fn italian_from_the_event_code() {
        // the generated table is sorted (binary search) and has the web interface's texts
        let it = NotifyLanguage::new("it").unwrap();
        assert!(TEXTS.iter().all(|(_, t)| t.windows(2).all(|w| w[0].0 < w[1].0)));
        assert_eq!(
            lookup(it, "nev.synodeb.unit_failed.title"),
            Some("Servizio non riuscito: {unit}")
        );
        assert_eq!(lookup(NotifyLanguage::EN, "nev.synodeb.unit_failed.title"), None);
        let t = Templates::new("nas");
        let mut e = n(1, EventState::Firing);
        e.code = "storage.raid_degraded".into();
        e.fields.extend([
            ("level".to_string(), "raid1".to_string()),
            ("state".to_string(), "clean, degraded".to_string()),
            ("degraded".to_string(), "1".to_string()),
            ("raid_disks".to_string(), "2".to_string()),
        ]);
        let ctx = t.event_ctx(&e, false, NotifyLanguage::new("it").unwrap(), utc);
        assert_eq!(ctx.title, "RAID md2 degradato");
        assert!(
            ctx.body.starts_with("md2 (raid1) è senza ridondanza"),
            "{}",
            ctx.body
        );
        // English targets keep the server's text
        let ctx = t.event_ctx(&e, false, NotifyLanguage::EN, utc);
        assert_eq!(
            (ctx.title.as_str(), ctx.body.as_str()),
            ("RAID md2 degraded", "1 of 2 members missing.")
        );
        // log bodies are sent as they are; a missing field keeps the English title
        let mut e = n(2, EventState::Oneshot);
        e.code = "synodeb.unit_failed".into();
        e.body_format = BodyFormat::Log;
        let ctx = t.event_ctx(&e, false, NotifyLanguage::new("it").unwrap(), utc);
        assert_eq!(
            (ctx.title.as_str(), ctx.body.as_str()),
            ("RAID md2 degraded", "1 of 2 members missing.")
        );
        e.fields.insert("unit".into(), "web-app.service".into());
        let ctx = t.event_ctx(&e, false, NotifyLanguage::new("it").unwrap(), utc);
        assert_eq!(ctx.title, "Servizio non riuscito: web-app.service");
        assert_eq!(ctx.body, "1 of 2 members missing.");
    }

    /// Every language of the table renders: its own words where its `notify.txt` has them,
    /// English otherwise; an unknown code renders in English and is refused for a target.
    #[test]
    fn any_language_of_the_table() {
        assert_eq!(LANGUAGES.first(), Some(&"en"));
        assert!(known_language(NotifyLanguage::EN));
        let unknown = NotifyLanguage::new("xx").unwrap();
        assert!(!known_language(unknown));
        assert_eq!(test_texts(unknown), (EN.test_title, EN.test_body));
        for code in LANGUAGES {
            let l = NotifyLanguage::new(code).unwrap();
            assert!(known_language(l));
            let t = Templates::new("nas");
            let m = t.render(vec![t.event_ctx(&n(1, EventState::Resolved), false, l, utc)], l);
            assert!(m.subject.starts_with("[nas] "), "{code}: {}", m.subject);
        }
    }

    /// The `notify.txt` of every language: each source key, nothing stale, the same
    /// placeholders (none today), no empty text.
    #[test]
    fn notify_translations_are_complete() {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../rynas-ui/assets/i18n");
        let src = notify_source();
        let mut bad = Vec::new();
        for code in LANGUAGES.iter().skip(1) {
            let Ok(text) = std::fs::read_to_string(dir.join(code).join("notify.txt")) else {
                bad.push(format!("{code}/notify.txt: no file"));
                continue;
            };
            let got: BTreeMap<&str, &str> = text
                .lines()
                .filter(|l| !l.starts_with('#'))
                .filter_map(|l| l.split_once('\t'))
                .collect();
            for (k, en) in &src {
                match got.get(k.as_str()) {
                    None => bad.push(format!("{code}/notify: {k}: missing")),
                    Some(t) if t.trim().is_empty() => bad.push(format!("{code}/notify: {k}: empty")),
                    Some(t) if t.matches('{').count() != en.matches('{').count() => {
                        bad.push(format!("{code}/notify: {k}: placeholders differ"))
                    }
                    Some(_) => {}
                }
            }
            for k in got.keys() {
                if !src.iter().any(|(s, _)| s == k) {
                    bad.push(format!("{code}/notify: {k}: stale (not in the source)"));
                }
            }
        }
        assert!(bad.is_empty(), "{bad:#?}");
    }
}

#!/bin/sh
# Golden next runs from systemd-analyze of Debian trixie (systemd 257): reads cases.txt
# (python3 cases.py > cases.txt), writes next.txt. Needs docker or podman and the network
# (apt in a throwaway debian:trixie container).
#
#   crates/rynas-schedule/tests/golden/gen.sh
#
# next.txt, one case per line, TAB separated:
#   tz  base  iterations  expression  normalized-or-"invalid"  next runs in UTC (space separated)
set -eu
here=$(cd "$(dirname "$0")" && pwd)
engine=$(command -v podman || command -v docker)
name=rynas-schedule-golden-$$
trap '"$engine" rm -f "$name" >/dev/null 2>&1 || true' EXIT
"$engine" run -d --name "$name" -v "$here:/golden" debian:trixie sleep 3600 >/dev/null
"$engine" exec "$name" sh -c 'apt-get update -qq >/dev/null && DEBIAN_FRONTEND=noninteractive apt-get install -y -qq systemd >/dev/null 2>&1'
"$engine" exec "$name" sh -c '
set -eu
v=$(systemd-analyze --version | head -1)
{
  echo "# $v, generated by gen.sh from cases.txt"
  grep -v "^#" /golden/cases.txt | while IFS="	" read -r tz base n expr; do
    epoch=$(date -u -d "$(echo "$base" | tr T " " | tr -d Z)" +%s)
    if out=$(TZ="$tz" systemd-analyze calendar --iterations="$n" --base-time="@$epoch" "$expr" 2>/dev/null); then
      norm=$(printf "%s\n" "$out" | sed -n "s/^Normalized form: //p")
      # each elapse line, or the "(in UTC):" line after it when systemd prints one (it does
      # not while the zone is at offset 0: then the local time is UTC)
      runs=$(printf "%s\n" "$out" | awk '"'"'
        /never$/ { next }
        /^ *(Next elapse|Iteration #[0-9]+):/ { if (p != "") print p; p = $(NF-2) "T" $(NF-1) "Z"; next }
        /^ *\(in UTC\):/ { p = $(NF-2) "T" $(NF-1) "Z"; next }
        END { if (p != "") print p }'"'"' | tr "\n" " " | sed "s/ $//")
    else
      norm=invalid; runs=
    fi
    printf "%s\t%s\t%s\t%s\t%s\t%s\n" "$tz" "$base" "$n" "$expr" "$norm" "$runs"
  done
} > /golden/next.txt
'
echo "wrote $here/next.txt"
"$engine" exec "$name" sh -c '
{
  echo "# $(systemd-analyze --version | head -1), generated by gen.sh from normalize-cases.txt"
  grep -v "^#" /golden/normalize-cases.txt | while IFS= read -r expr; do
    if out=$(TZ=UTC systemd-analyze calendar "$expr" 2>/dev/null); then
      norm=$(printf "%s\n" "$out" | sed -n "s/^Normalized form: //p")
    else
      norm=invalid
    fi
    printf "%s\t%s\n" "$expr" "$norm"
  done
} > /golden/normalize.txt
'
"$engine" exec "$name" chown "$(id -u):$(id -g)" /golden/next.txt /golden/normalize.txt
echo "wrote $here/normalize.txt"
